    public UiLocalization() => SetLanguage("en-US");

    public string Language { get; private set; } = "en-US";
    public UiText Text { get; private set; } = null!;

    public void SetLanguage(string language)
    {
        Language = Translations.ContainsKey(language) ? language : "en-US";
        Text = new UiText(this);
        var culture = CultureInfo.GetCultureInfo(Language);
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
    }

    public string Get(string key)
    {
        if (Translations[Language].TryGetValue(key, out var localized))
            return localized;
        return Translations["en-US"].TryGetValue(key, out var english) ? english : key;
    }

    public string Format(string key, params object[] args) =>
        string.Format(CultureInfo.CurrentCulture, Get(key), args);
}

